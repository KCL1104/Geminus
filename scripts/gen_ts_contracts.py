#!/usr/bin/env python3
"""Generate apps/web/lib/contracts/*.ts from schemas/*.schema.json (T-003).

The schemas stay the source of truth: these types mirror value shapes only.
Ranges, patterns, formats and if/then rules are not expressible in TypeScript
and remain the job of the schema and semantic validators.

  python3 scripts/gen_ts_contracts.py          # write
  python3 scripts/gen_ts_contracts.py --check  # fail if the committed files are stale

Fails closed on any schema keyword it does not know.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'apps/web/lib/contracts'
HEADER = ('// GENERATED by scripts/gen_ts_contracts.py from schemas/{name}. DO NOT EDIT.\n'
          '// Value shapes only: ranges, patterns and cross-field rules are enforced by the\n'
          '// schema and semantic validators, not by these types.\n')
SHAPE = {'type', 'properties', 'required', 'additionalProperties', 'items', 'enum', 'const',
         'oneOf', 'anyOf', 'allOf', '$ref'}
# Validation-only keywords: they narrow values without changing their shape.
# dependentRequired, propertyNames and minProperties came with T-046 phase 2
# (ADR-026 members); like the rest they stay the validators' job.
IGNORED = {'$schema', '$id', '$comment', '$defs', 'title', 'description', 'minimum', 'maximum',
           'exclusiveMinimum', 'exclusiveMaximum', 'minLength', 'maxLength', 'pattern', 'format',
           'minItems', 'maxItems', 'uniqueItems', 'maxProperties', 'minProperties', 'propertyNames',
           'dependentRequired', 'if', 'then', 'not', 'x-http-status'}
ROOT_NAMES = {'ai-mapping': 'AiMapping', 'analysis-output': 'AnalysisOutput',
              'canonical-event': 'CanonicalEvent', 'dataset-snapshot': 'DatasetSnapshot',
              'import': 'Import', 'import-mapping': 'ImportMapping', 'json-patch': 'JsonPatch', 'model-ir': 'ModelIR',
              'proposal': 'Proposal', 'proposal-output': 'ProposalOutput', 'scenario': 'Scenario'}
IDENT = re.compile(r'^[A-Za-z_$][A-Za-z0-9_$]*$')


class Gen:
    def __init__(self, stem):
        self.stem = stem
        self.imports = {}  # module stem -> names

    def ref(self, ref):
        file, _, frag = ref.partition('#')
        stem = file.removesuffix('.schema.json') if file else self.stem
        if frag:
            m = re.fullmatch(r'/\$defs/([A-Za-z0-9]+)', frag)
            if not m:
                raise ValueError(f'{self.stem}: unsupported $ref {ref}')
            name = m.group(1)
        else:
            name = ROOT_NAMES[stem]
        if stem != self.stem:
            self.imports.setdefault(stem, set()).add(name)
        return name

    def ts(self, s, indent=0):
        unknown = set(s) - SHAPE - IGNORED
        if unknown:
            raise ValueError(f'{self.stem}: unsupported keywords {sorted(unknown)}')
        if '$ref' in s:
            return self.ref(s['$ref'])
        if 'const' in s:
            return json.dumps(s['const'], ensure_ascii=False)
        if 'enum' in s:
            return ' | '.join(json.dumps(v, ensure_ascii=False) for v in s['enum'])
        for key in ('oneOf', 'anyOf'):
            alts = [a for a in s.get(key, []) if set(a) & (SHAPE - {'required'})]
            if alts and 'properties' not in s and 'type' not in s:
                return ' | '.join(self.wrap(self.ts(a, indent)) for a in alts)
        if 'allOf' in s and 'type' not in s and 'properties' not in s:
            parts = [self.ts(a, indent) for a in s['allOf'] if set(a) & SHAPE - {'required'}]
            if not parts:
                raise ValueError(f'{self.stem}: allOf without a value shape')
            return ' & '.join(self.wrap(p) for p in parts)
        ty = s.get('type')
        if isinstance(ty, list):
            raise ValueError(f'{self.stem}: type arrays are not used; use anyOf')
        if ty in ('string', 'boolean', 'null'):
            return ty
        if ty in ('number', 'integer'):
            return 'number'
        if ty == 'array':
            return self.wrap(self.ts(s['items'], indent)) + '[]'
        if ty == 'object' or 'properties' in s:
            return self.obj(s, indent)
        if not set(s) & SHAPE:
            return 'unknown'  # e.g. a JSON Patch value: any JSON
        raise ValueError(f'{self.stem}: cannot map {json.dumps(s)[:120]}')

    def obj(self, s, indent):
        props = s.get('properties', {})
        extra = s.get('additionalProperties', True)
        if not props:
            if extra is False:
                return 'Record<string, never>'  # a closed empty object: no member at all
            value = self.ts(extra, indent) if isinstance(extra, dict) else 'unknown'
            return f'Record<string, {value}>'
        pad, inner = '  ' * indent, '  ' * (indent + 1)
        required = set(s.get('required', []))
        lines = []
        for name, sub in props.items():
            key = name if IDENT.match(name) else json.dumps(name)
            opt = '' if name in required else '?'
            doc = sub.get('description')
            if doc:
                lines.append(f'{inner}/** {doc} */')
            lines.append(f'{inner}{key}{opt}: {self.ts(sub, indent + 1)};')
        if isinstance(extra, dict):
            lines.append(f'{inner}[key: string]: {self.ts(extra, indent + 1)};')
        return '{\n' + '\n'.join(lines) + f'\n{pad}}}'

    @staticmethod
    def wrap(t):
        """Parenthesize t when it is a top-level union or intersection."""
        depth, quoted = 0, False
        for i, ch in enumerate(t):
            if ch == '"' and (i == 0 or t[i - 1] != '\\'):
                quoted = not quoted
            elif not quoted and ch in '{([':
                depth += 1
            elif not quoted and ch in '})]':
                depth -= 1
            elif not quoted and depth == 0 and t[i:i + 3] in (' | ', ' & '):
                return f'({t})'
        return t


def render(path):
    stem = path.name.removesuffix('.schema.json')
    doc = json.loads(path.read_text(encoding='utf-8'))
    g = Gen(stem)
    body = []
    if stem in ROOT_NAMES:
        body.append(f'export type {ROOT_NAMES[stem]} = {g.ts(doc)};\n')
    for name, sub in doc.get('$defs', {}).items():
        doc_line = f'/** {sub["description"]} */\n' if sub.get('description') else ''
        body.append(f'{doc_line}export type {name} = {g.ts(sub)};\n')
    head = HEADER.format(name=path.name)
    imports = ''.join(f'import type {{ {", ".join(sorted(names))} }} from "./{mod}";\n'
                      for mod, names in sorted(g.imports.items()))
    return stem, head + (imports + '\n' if imports else '\n') + '\n'.join(body)


def main():
    check = '--check' in sys.argv
    files, exported = {}, {}
    for path in sorted((ROOT / 'schemas').glob('*.schema.json')):
        stem, text = render(path)
        files[f'{stem}.ts'] = text
        for name in re.findall(r'^export type (\w+)', text, re.M):
            if name in exported:
                raise ValueError(f'type {name} exported by both {exported[name]} and {stem}')
            exported[name] = stem
    index = HEADER.format(name='*.schema.json') + '\n' + ''.join(
        f'export type * from "./{f.removesuffix(".ts")}";\n' for f in sorted(files))
    files['index.ts'] = index
    if check:
        stale = sorted(n for n, t in files.items()
                       if not (OUT / n).is_file() or (OUT / n).read_text(encoding='utf-8') != t)
        extra = sorted(p.name for p in OUT.glob('*.ts') if p.name not in files) if OUT.is_dir() else []
        if stale or extra:
            print(f'STALE TS contracts: {stale} extra: {extra}; run python3 scripts/gen_ts_contracts.py',
                  file=sys.stderr)
            sys.exit(1)
        print(json.dumps({'status': 'PASS_TS_CONTRACTS_FRESH', 'files': len(files), 'types': len(exported)}))
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob('*.ts'):
        if p.name not in files:
            p.unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding='utf-8')
    print(f'wrote {len(files)} files, {len(exported)} types to {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
