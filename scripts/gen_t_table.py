#!/usr/bin/env python3
"""Generate internal/results/metrics/ttable.go: two-sided 95% Student-t critical
values t_{0.975, df} for df = 1..999 (runs have at most 1000 replications).

The values are fixed constants so the confidence interval, and with it the
result digest, does not depend on a platform's math library. Generated with
scipy.stats.t.ppf; run with a Python that has scipy:

    python scripts/gen_t_table.py > internal/results/metrics/ttable.go
"""
import scipy
from scipy.stats import t

print("// Code generated by scripts/gen_t_table.py (scipy %s, scipy.stats.t.ppf(0.975, df)); DO NOT EDIT." % scipy.__version__)
print()
print("package metrics")
print()
print("// studentT975[df] is the two-sided 95% Student-t critical value for df")
print("// degrees of freedom, df = 1..999; index 0 is unused.")
print("var studentT975 = [1000]float64{")
print("\t0,")
for df in range(1, 1000):
    print("\t%r," % float(t.ppf(0.975, df)))
print("}")
