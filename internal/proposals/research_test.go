// H-046 (2): a request that asks for research where this deployment's
// provider may not search is refused with the proposals' code for its
// availability and AI_RESEARCH_UNSUPPORTED at /research.
func TestResearchRefusal(t *testing.T) {
	for a, want := range map[Availability]httpapi.Code{NotConfigured: httpapi.AIProviderNotConfigured, PolicyNotApproved: httpapi.AIPolicyNotApproved} {
		var he *httpapi.Error
		if !errors.As(Refused(&UnavailableError{Availability: a, Research: true}), &he) || he.Code != want || len(he.Details) != 1 ||
			he.Details[0].Code != CodeResearchUnsupported || he.Details[0].Path != "/research" {
			t.Errorf("%v: %+v", a, he)
		}
		if msg := (&UnavailableError{Availability: a, Research: true}).Error(); !strings.Contains(msg, CodeResearchUnsupported) {
			t.Errorf("%v: %q", a, msg)
		}
	}
	if CodeResearchUnsupported != "AI_"+strings.ToUpper(string(provider.CodeResearchUnsupported)) {
		t.Error("the API's code is not the job's")
	}
	if errorCodes[CodeResearchUnsupported] != "AI_PROVIDER_NOT_CONFIGURED" {
		t.Error("a failed research job is not shown as AI_PROVIDER_NOT_CONFIGURED")
	}
}

const researchedMeta = `{"provider":"meta","model":"muse-spark-1.3","credential_label":"meta","cost_nano_usd":5,
	"web_search":{"queries":4,"tool_calls":9,"pages_opened":3,"sources_kept":2,"sources_dropped":1},
	"sources":[{"url":"https://example.com/a","title":"A page"},{"url":"https://example.org/b"}]}`

// The resource shows the web search's queries and dropped count and the
// kept sources, from the stored metadata, and checks them again as the
// contract states them: a stored value outside it is left out, never shown.
func TestResearchInTheResource(t *testing.T) {
	g := FromMetadata([]byte(researchedMeta))
	if g == nil || g.WebSearch == nil || *g.WebSearch != (GeneratedWebSearch{Queries: 4, SourcesDropped: 1}) {
		t.Fatalf("generated by %+v", g)
	}
	out, _ := json.Marshal(g)
	for _, leak := range []string{"tool_calls", "pages_opened", "sources_kept", "credential", "cost", "example"} {
		if strings.Contains(string(out), leak) {
			t.Errorf("%s leaks %q", out, leak)
		}
	}
	for name, metadata := range map[string]string{
		"no web search":    `{"provider":"meta"}`,
		"negative queries": `{"provider":"meta","web_search":{"queries":-1,"sources_dropped":0}}`,
		"too many queries": `{"provider":"meta","web_search":{"queries":10001,"sources_dropped":0}}`,
		"too many dropped": `{"provider":"meta","web_search":{"queries":1,"sources_dropped":21}}`,
	} {
		if g := FromMetadata([]byte(metadata)); g == nil || g.WebSearch != nil {
			t.Errorf("%s: %+v", name, g)
		}
	}
	want := []provider.WebSource{{URL: "https://example.com/a", Title: "A page"}, {URL: "https://example.org/b"}}
	if got := SourcesOf([]byte(researchedMeta)); !slices.Equal(got, want) {
		t.Errorf("sources %+v", got)
	}
	for name, metadata := range map[string]string{
		"without a web search": `{"provider":"meta","sources":[{"url":"https://example.com/a"}]}`,
		"http":                 `{"provider":"meta","web_search":{"queries":1},"sources":[{"url":"http://example.com/a"}]}`,
		"script":               `{"provider":"meta","web_search":{"queries":1},"sources":[{"url":"javascript:alert(1)"}]}`,
		"not canonical":        `{"provider":"meta","web_search":{"queries":1},"sources":[{"url":"HTTPS://EXAMPLE.COM/a"}]}`,
		"a hidden character":   `{"provider":"meta","web_search":{"queries":1},"sources":[{"url":"https://example.com/a","title":"a\u200bb"}]}`,
		"an empty URL":         `{"provider":"meta","web_search":{"queries":1},"sources":[{"title":"x"}]}`,
		"not JSON":             `{`,
	} {
		if got := SourcesOf([]byte(metadata)); got != nil {
			t.Errorf("%s: %+v", name, got)
		}
	}
	var many strings.Builder
	many.WriteString(`{"provider":"meta","web_search":{"queries":1},"sources":[`)
	for i := range 25 {
		if i > 0 {
			many.WriteString(",")
		}
		many.WriteString(`{"url":"https://example.com/` + strings.Repeat("p", i+1) + `"}`)
	}
	many.WriteString("]}")
	if got := SourcesOf([]byte(many.String())); len(got) != provider.MaxSources {
		t.Errorf("%d sources shown", len(got))
	}
}

// Review round 1, M1: a research proposal's job has a single attempt, so a
// research call that timed out or failed is never run (and billed) again on
// its own; a proposal without research keeps the queue's attempts and a
// payload without research.
func TestResearchJobIsOneAttempt(t *testing.T) {
	const org, id, req = "org_01M4YDQK00Y5H2929M9WWZWTVH", "aip_01M4YDQK00ADN261CME3WV5HZ6", "req_01M4YDQK00ADN261CME3WV5HZ6"
	j := proposalJob(org, id, req, true)
	if j.MaxAttempts != 1 || ResearchJobAttempts != 1 || j.Payload["research"] != true || j.Resource.AIProposalID != id || j.OrganizationID != org {
		t.Errorf("research job %+v", j)
	}
	j = proposalJob(org, id, req, false)
	if _, ok := j.Payload["research"]; ok || j.MaxAttempts != 0 || j.Payload["proposal_id"] != id || j.Payload["request_id"] != req {
		t.Errorf("job without research %+v", j)
	}
}

// Review round 1, L1: sources are served only with the web search the
// resource shows: where FromMetadata leaves web_search (or all of
// generated_by) out, SourcesOf shows no source either, so proposal.schema.json's
// "sources only with generated_by.web_search" always holds.
func TestSourcesOnlyWithTheWebSearchShown(t *testing.T) {
	src := `"sources":[{"url":"https://example.com/a"}]`
	for name, metadata := range map[string]string{
		"too many queries":             `{"provider":"meta","web_search":{"queries":10001,"sources_dropped":0},` + src + `}`,
		"too many dropped":             `{"provider":"meta","web_search":{"queries":1,"sources_dropped":21},` + src + `}`,
		"negative queries":             `{"provider":"meta","web_search":{"queries":-1,"sources_dropped":0},` + src + `}`,
		"a provider outside its shape": `{"provider":"Meta AI","web_search":{"queries":1,"sources_dropped":0},` + src + `}`,
		"no provider":                  `{"web_search":{"queries":1,"sources_dropped":0},` + src + `}`,
	} {
		g := FromMetadata([]byte(metadata))
		if got := SourcesOf([]byte(metadata)); got != nil || (g != nil && g.WebSearch != nil) {
			t.Errorf("%s: sources %+v with generated by %+v", name, got, g)
		}
	}
	ok := `{"provider":"meta","web_search":{"queries":1,"sources_dropped":0},` + src + `}`
	if g := FromMetadata([]byte(ok)); g == nil || g.WebSearch == nil || len(SourcesOf([]byte(ok))) != 1 {
		t.Errorf("the good case: %+v %+v", g, SourcesOf([]byte(ok)))
	}
}

// Sources are shown in the states that keep what the provider wrote, and
// the resource is valid under proposal.schema.json; never for an invalid,
// failed or generating proposal.
func TestResearchStates(t *testing.T) {
	base := store.Proposal{ID: "aip_01M4YDQK00ADN261CME3WV5HZ6", OrganizationID: "org_01M4YDQK00Y5H2929M9WWZWTVH",
		ModelID: "mdl_01M4YDQK00ADN261CME3WV5HZ6", BaseVersionID: "mv_01M4YDQK00ADN261CME3WV5HZ6", Mode: "edit",
		CreatedBy: "usr_01M4YDQK00ADN261CME3WV5HZ6", ProviderMetadata: []byte(researchedMeta)}
	summary := "Which flute?"
	needs := base
	needs.Status, needs.Summary, needs.Assumptions, needs.Questions = store.NeedsInput, &summary, []string{}, []string{"Which flute?"}
	p, err := Public(needs, "req_01M4YDQK00ADN261CME3WV5HZ6")
	if err != nil {
		t.Fatal(err)
	}
	if len(p.Sources) != 2 || p.GeneratedBy == nil || p.GeneratedBy.WebSearch == nil {
		t.Errorf("needs_input: %+v %+v", p.Sources, p.GeneratedBy)
	}
	data, _ := json.Marshal(p)
	if issues, err := validate.Document(data, "proposal.schema.json", "RESPONSE"); err != nil || len(issues) > 0 {
		t.Errorf("needs_input does not match the schema: %v %v\n%s", issues, err, data)
	}
	invalid := base
	invalid.Status, invalid.Validation = store.Invalid, []byte(`{"valid":false,"issues":[{"code":"AI_OUTPUT_INVALID","path":"","message":"x","severity":"error"}]}`)
	if p, err := Public(invalid, ""); err != nil || p.Sources != nil {
		t.Errorf("invalid: %+v %v", p.Sources, err)
	}
	generating := base
	generating.Status, generating.ProviderMetadata = store.Generating, []byte(`{}`)
	if p, err := Public(generating, ""); err != nil || p.Sources != nil || p.GeneratedBy != nil {
		t.Errorf("generating: %+v %v", p, err)
	}
}
