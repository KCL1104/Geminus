// The photo pipeline (T-056, H-029, H-033): a proposal asked for with a
// photo or floor plan (it has an image record, migration 0017, and no
// intent) is generated by generatePhoto instead of generate. Under the
// same rules: the dataset snapshots are read before any AI call, AI calls
// run outside every transaction through the checked (and, live, metered)
// clients, and the outcome is written only with the job's completion.
//
//  1. The model's pack must name what a segmenter looks for
//     (domainpack.PhotoVocabulary), else PHOTO_NOT_SUPPORTED.
//  2. The stored image is read from private storage and checked against
//     its record (photo.Verify: hash, size, type, pixels) before it goes
//     anywhere: PHOTO_STORAGE_FAILED when it cannot be read (retried),
//     PHOTO_CORRUPT when it is not the record's.
//  3. The segmenter (Config.Segmenter: SAM 3.1 behind T-055's adapter; the
//     fake in tests) finds the boxes for the pack's prompts; the client
//     checks them. A box the server refuses makes the proposal invalid; no
//     box makes it needs_input with the server's own question, and the
//     vision model is never asked.
//  4. The vision model (Config.Provider as a provider.ImageProposer: Muse
//     Spark behind T-055's adapter, or Claude's image input as the
//     fallback; the fake in tests) proposes the stations and flow from the
//     image and the boxes (aicontext.ImageProposal).
//  5. The server reviews the answer as any edit (review.Review), then the
//     photo rules (review.Photo: no more new process steps than boxes, no
//     number of its own), then the dataset binding stage.

// Failure codes of the photo pipeline (jobs.Failure.Code).
const (
	// PhotoNotSupported: the model's domain pack names nothing a segmenter
	// could look for in a photo (never retried).
	PhotoNotSupported = "PHOTO_NOT_SUPPORTED"
	// PhotoStorageFailed: the stored image could not be read (retried: no
	// AI call was made yet), or this worker has no object storage (not
	// retried).
	PhotoStorageFailed = "PHOTO_STORAGE_FAILED"
	// PhotoCorrupt: the stored image is missing or is not the one its
	// record names, or its key is not the organization's (never retried:
	// nothing is forwarded).
	PhotoCorrupt = "PHOTO_CORRUPT"
)

// Segmenter finds the boxes of what a photo shows; *vision.Client is one.
type Segmenter interface {
	Segment(ctx context.Context, in vision.Input) (vision.Result, error)
}

var _ Segmenter = (*vision.Client)(nil)

// photoCall is what an attempt of a photo proposal knows of its image and
// its segmenter call, for the stored metadata and the audit.
type photoCall struct {
	image     store.Image
	segmenter *vision.Metadata // nil before the segmenter was asked
}

// noBoxes is the server's request for input when the segmenter found
// nothing: the photo shows no station to propose.
func noBoxes(outputLocale string) review.Outcome {
	summary := "The segmenter found no machine, conveyor or workstation in the photo, so no station can be proposed from it."
	question := "Which stations does the line have, in which order? Upload a clearer photo or floor plan of the line, or describe it in words."
	if outputLocale == string(locale.TraditionalChinese) {
		summary = "影像辨識在這張照片中找不到機台、輸送帶或工作站，無法從照片提出工作站。"
		question = "這條產線有哪些工作站、順序為何？請上傳更清楚的產線照片或平面圖，或以文字描述產線。"
	}
	return review.Outcome{Status: review.NeedsInput, Summary: summary, Assumptions: []string{}, Questions: []string{question}}
}

// readImage reads the proposal's stored image and checks it against its
// record.
func (h *Handler) readImage(ctx context.Context, org string, im store.Image) (provider.Image, error) {
	if h.cfg.Objects == nil {
		return provider.Image{}, failure(PhotoStorageFailed, "the proposal has a photo and this worker has no object storage", false)
	}
	if !objects.InArea(org, objects.Assets, im.ObjectKey) {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo's key is not one the server makes for the organization", false)
	}
	rc, err := h.cfg.Objects.Get(ctx, im.ObjectKey)
	if errors.Is(err, objects.ErrNotFound) {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo is missing", false)
	}
	var data []byte
	if err == nil {
		data, err = io.ReadAll(io.LimitReader(rc, photo.MaxBytes+1))
		if cerr := rc.Close(); err == nil {
			err = cerr
		}
	}
	if err != nil {
		if ctx.Err() != nil {
			return provider.Image{}, ctx.Err()
		}
		h.cfg.Log.WarnContext(ctx, "reading a proposal's photo failed", "organization_id", org, "error", err.Error())
		return provider.Image{}, failure(PhotoStorageFailed, "the stored photo could not be read", true)
	}
	if photo.Verify(data, photo.Record{MediaType: im.MediaType, Width: im.Width, Height: im.Height, Size: im.Size, SHA256: im.SHA256}) != nil {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo is not the one its record names", false)
	}
	return provider.Image{MediaType: im.MediaType, Data: data, Width: im.Width, Height: im.Height, SHA256: im.SHA256}, nil
}

// generatePhoto is generate for a proposal asked for with a photo.
func (h *Handler) generatePhoto(ctx context.Context, org string, st started, attr provider.Attribution) (generation, error) {
	pr, v := st.proposal, st.version
	if pr.Image == nil || pr.Mode != string(provider.ModeEdit) || pr.Intent != "" {
		return generation{}, failure(InputInvalid, "a photo proposal is an edit with an image and no intent", false)
	}
	pc := &photoCall{image: *pr.Image}
	var ir model.ModelIR
	if err := model.Decode(v.IR, &ir); err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the base version does not decode", false)
	}
	pack, err := h.cfg.Packs.Lookup(ir.Domain)
	if err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the model's domain is not served by this worker", false)
	}
	vocab, ok := pack.(domainpack.PhotoVocabulary)
	if !ok || len(vocab.PhotoPrompts()) == 0 {
		return generation{photo: pc}, failure(PhotoNotSupported, "the model's domain takes no photos: describe the change in words", false)
	}
	prompts := vocab.PhotoPrompts()
	proposer, ok := h.cfg.Provider.(provider.ImageProposer)
	if !ok || h.cfg.Segmenter == nil {
		return generation{photo: pc}, failure("AI_"+strings.ToUpper(string(provider.CodeNotConfigured)), providerMessages[provider.CodeNotConfigured], false)
	}
	var pool idpool.Pool
	if err := json.Unmarshal(pr.IDPool, &pool); err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the stored ID pool does not decode", false)
	}
	snaps, err := h.preload(ctx, org, st)
	if err != nil {
		return generation{photo: pc}, err
	}
	manifest, err := h.verify(ctx, org, pr.ID, snaps, &ir, v.DatasetBindings)
	if err != nil {
		return generation{photo: pc}, err
	}
	img, err := h.readImage(ctx, org, *pr.Image)
	if err != nil {
		return generation{photo: pc}, err
	}

	seg, err := h.cfg.Segmenter.Segment(ctx, vision.Input{OrganizationID: org, Image: img, Prompts: prompts, Attribution: attr})
	pc.segmenter = &seg.Metadata
	h.logSegment(ctx, seg.Metadata, err)
	if err != nil {
		if ctx.Err() != nil {
			return generation{}, err
		}
		var pe *provider.Error
		if errors.As(err, &pe) && pe.Code == provider.CodeInvalidOutput {
			return generation{outcome: review.InvalidOutput(pe.Issues), photo: pc, manifest: manifest}, nil
		}
		return generation{photo: pc}, providerFailure(err)
	}
	if len(seg.Boxes) == 0 {
		return generation{outcome: noBoxes(pr.OutputLocale), photo: pc, manifest: manifest}, nil
	}

	in := aicontext.ImageProposalInput{
		Scope:        aicontext.Scope{OrganizationID: org, ModelID: pr.ModelID},
		Base:         aicontext.Version{OrganizationID: org, ModelID: v.ModelID, VersionID: v.ID, IR: &ir},
		Domain:       pack.PromptContext(),
		Pool:         aicontext.Pool{OrganizationID: org, ProposalID: pr.ID, IDs: pool},
		Photo:        aicontext.Photo{OrganizationID: org, Image: img.Ref(), Prompts: prompts, Boxes: seg.Boxes},
		OutputLocale: pr.OutputLocale,
		Budget:       h.cfg.Budget,
	}
	pctx, err := aicontext.ImageProposal(in)
	if err != nil {
		if aicontext.CodeOf(err) == aicontext.TooLarge {
			return generation{photo: pc}, failure("AI_CONTEXT_TOO_LARGE", providerMessages[provider.CodeContextTooLarge], false)
		}
		h.cfg.Log.WarnContext(ctx, "building a photo proposal context failed", "organization_id", org, "proposal_id", pr.ID, "code", string(aicontext.CodeOf(err)))
		return generation{photo: pc}, failure(InputInvalid, "the proposal's stored request cannot be built into a context", false)
	}
	res, err := proposer.GenerateImageProposal(ctx, provider.ImageProposalContext{OrganizationID: org, Prompt: pctx.Prompt, Image: img, Attribution: attr})
	meta := res.Metadata
	h.logCall(ctx, meta, err)
	if err != nil {
		if ctx.Err() != nil {
			return generation{}, err
		}
		var pe *provider.Error
		if errors.As(err, &pe) && pe.Code == provider.CodeInvalidOutput {
			return generation{outcome: review.InvalidOutput(pe.Issues), meta: &meta, photo: pc, manifest: manifest}, nil
		}
		return generation{meta: &meta, photo: pc}, providerFailure(err)
	}
	outcome, err := review.Review(review.Input{Mode: provider.ModeEdit, Base: v.IR, Pool: pool, Pack: pack, Output: res.Output})
	if err != nil {
		h.cfg.Log.ErrorContext(ctx, "reviewing a photo proposal failed", "organization_id", org, "proposal_id", pr.ID, "error", err.Error())
		return generation{meta: &meta, photo: pc}, failure(InputInvalid, "the server could not review the answer against the stored base", false)
	}
	if outcome.Status == review.Ready {
		outcome = outcome.Refuse(review.Photo(&ir, outcome.Candidate, len(seg.Boxes)))
	}
	if outcome.Status != review.Ready {
		return generation{outcome: outcome, meta: &meta, photo: pc, manifest: manifest}, nil
	}
	resolution, err := datasets.Resolve(ctx, snaps, org, outcome.Candidate, v.DatasetBindings)
	if err != nil {
		if ctx.Err() != nil {
			return generation{}, err
		}
		h.cfg.Log.ErrorContext(ctx, "the dataset binding stage failed after the provider answered", "organization_id", org, "proposal_id", pr.ID, "error", err.Error())
		return generation{meta: &meta, photo: pc}, failure(DatasetStorageFailed, "the dataset binding stage failed after the provider answered", false)
	}
	return generation{outcome: outcome.Refuse(withoutIR(resolution.Issues)), meta: &meta, photo: pc, manifest: manifest}, nil
}

// logSegment is the segmenter call's operational line: labels, counts,
// latency, cost and the outcome code; never the image, a box or a label.
func (h *Handler) logSegment(ctx context.Context, m vision.Metadata, err error) {
	code := "OK"
	switch c := provider.CodeOf(err); {
	case err == nil:
	case c == "":
		code = "ERROR"
	default:
		code = "AI_" + strings.ToUpper(string(c))
	}
	h.cfg.Log.InfoContext(ctx, "ai segmenter call ended", "provider", m.Provider, "model", m.Model, "credential_label", m.Credential,
		"latency_ms", m.LatencyMillis, "boxes", m.Boxes, "provider_request_id", m.ProviderRequestID, "code", code,
		"cost_nano_usd", m.CostNanoUSD, "spend_reservation_id", m.SpendReservation)
	if m.SpendUnsettled {
		h.cfg.Log.WarnContext(ctx, "settling a live AI spend reservation failed", "spend_reservation_id", m.SpendReservation,
			"cost_nano_usd", m.CostNanoUSD, "spend_unsettled", true)
	}
}

// photoImage is what the stored metadata says of the image.
type photoImage struct {
	SHA256    string `json:"sha256"`
	MediaType string `json:"media_type"`
	Width     int    `json:"width"`
	Height    int    `json:"height"`
}

// photoMetadata is a photo proposal's provider metadata: the vision model's
// call (base, the generated row's provider_metadata), the image by its
// hash, type and size, and the segmenter's call.
func photoMetadata(base []byte, g generation) ([]byte, error) {
	if g.photo == nil {
		return base, nil
	}
	var doc map[string]jsontext.Value
	if err := json.Unmarshal(base, &doc); err != nil {
		return nil, err
	}
	im := g.photo.image
	image, err := json.Marshal(photoImage{SHA256: im.SHA256, MediaType: im.MediaType, Width: im.Width, Height: im.Height})
	if err != nil {
		return nil, err
	}
	doc["image"] = image
	if g.photo.segmenter != nil {
		seg, err := json.Marshal(g.photo.segmenter)
		if err != nil {
			return nil, err
		}
		doc["segmenter"] = seg
	}
	return json.Marshal(doc, json.Deterministic(true))
}

// photoAuditMeta is auditMeta with what the audit records of the image and
// the segmenter's call (audit's photoCall fields): never the image, a box
// or a label.
func photoAuditMeta(m provider.Metadata, p *photoCall) map[string]any {
	out := auditMeta(m)
	if p == nil {
		return out
	}
	out["image_content_hash"] = p.image.SHA256
	if s := p.segmenter; s != nil {
		out["segmenter"], out["segmenter_boxes"], out["segmenter_latency_ms"] = audit.Label(s.Provider), s.Boxes, s.LatencyMillis
		if l := audit.Label(s.Model); l != "" {
			out["segmenter_model"] = l
		}
		if s.SpendReservation != "" {
			out["segmenter_cost_nano_usd"], out["segmenter_spend_reservation_id"] = s.CostNanoUSD, s.SpendReservation
		}
	}
	return out
}
