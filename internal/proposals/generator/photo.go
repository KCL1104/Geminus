// The photo pipeline (T-056, H-029, H-033), on T-055's provider.Image and
// provider.Segmenter: a proposal asked for with a photo or floor plan (it
// has an image record, migration 0017, and no intent) is generated by
// generatePhoto instead of generate. Under the same rules: the dataset
// snapshots are read before any AI call, AI calls run outside every
// transaction through the checked (and, live, metered) clients, and the
// outcome is written only with the job's completion.
//
//  1. The model's pack must name what a segmenter looks for
//     (domainpack.PhotoVocabulary), else PHOTO_NOT_SUPPORTED. The vision
//     client must take images (provider.Client.AcceptsImages), else
//     AI_IMAGE_UNSUPPORTED, before anything is spent.
//  2. The stored image is read from private storage and checked against
//     its record (photo.Verify: digest, size, type, pixels) and made a
//     provider.Image before it goes anywhere: PHOTO_STORAGE_FAILED when it
//     cannot be read (retried), PHOTO_CORRUPT when it is not the record's.
// Steps 3 to 5 are internal/ai/photopipeline (Propose), which the live
// photo smoke (cmd/ai-eval-live -smoke-photo) runs too:
//
//  3. The segmenter (Config.Segmenter: T-055's provider.SegmentClient over
//     SAM 3.1, metered; the fake in tests) finds the pack's concepts; the
//     client checks every answer, and the pipeline takes at most
//     review.MaxPhotoSegments in the image's own frame. A segmentation the
//     server refuses makes the proposal invalid; no segment makes it
//     needs_input with the server's own question, and the vision model is
//     never asked.
//  4. The vision model (Config.Vision, T-055's judge: Muse Spark behind its
//     adapter, or Claude's image input as the fallback once its adapter
//     takes images; the fake in tests) proposes the stations and flow from the image and
//     the segments (aicontext.ImageProposal: the image is the prompt's
//     image part).
//  5. The server reviews the answer as any edit (review.Review), then the
//     photo rules (review.Photo: no more new process steps than segments,
//     no number of its own), then the dataset binding stage.

// Failure codes of the photo pipeline (jobs.Failure.Code).
const (
	// PhotoNotSupported: the model's domain pack names nothing a segmenter
	// could look for in a photo (never retried).
	PhotoNotSupported = "PHOTO_NOT_SUPPORTED"
	// PhotoStorageFailed: the stored image could not be read (retried: no
	// AI call was made yet), or this worker has no object storage (not
	// retried).
	PhotoStorageFailed = "PHOTO_STORAGE_FAILED"
	// PhotoCorrupt: the stored image is missing or is not the one its
	// record names, or its key is not the organization's (never retried:
	// nothing is forwarded).
	PhotoCorrupt = "PHOTO_CORRUPT"
	// ImageUnsupported: the configured vision client does not take images
	// (the Anthropic adapter until the fallback is wired), or it is off
	// (T-055's photo path off: a Disabled backend); refused before the
	// segmenter is asked (never retried).
	ImageUnsupported = "AI_IMAGE_UNSUPPORTED"
)

// photoCall is what an attempt of a photo proposal knows of its image and
// its segmentation, for the stored metadata and the audit.
type photoCall struct {
	image store.Image
	// segmenter is nil before the segmenter was asked; segments is how
	// many objects its checked answer has.
	segmenter *provider.SegmentMetadata
	segments  int
}

// readImage reads the proposal's stored image, checks it against its
// record and makes it a provider.Image.
func (h *Handler) readImage(ctx context.Context, org string, im store.Image) (provider.Image, error) {
	if h.cfg.Objects == nil {
		return provider.Image{}, failure(PhotoStorageFailed, "the proposal has a photo and this worker has no object storage", false)
	}
	if !objects.InArea(org, objects.Assets, im.ObjectKey) {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo's key is not one the server makes for the organization", false)
	}
	rc, err := h.cfg.Objects.Get(ctx, im.ObjectKey)
	if errors.Is(err, objects.ErrNotFound) {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo is missing", false)
	}
	var data []byte
	if err == nil {
		data, err = io.ReadAll(io.LimitReader(rc, photo.MaxBytes+1))
		if cerr := rc.Close(); err == nil {
			err = cerr
		}
	}
	if err != nil {
		if ctx.Err() != nil {
			return provider.Image{}, ctx.Err()
		}
		h.cfg.Log.WarnContext(ctx, "reading a proposal's photo failed", "organization_id", org, "error", err.Error())
		return provider.Image{}, failure(PhotoStorageFailed, "the stored photo could not be read", true)
	}
	if photo.Verify(data, photo.Record{MediaType: im.MediaType, Width: im.Width, Height: im.Height, Size: im.Size, SHA256: im.SHA256}) != nil {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo is not the one its record names", false)
	}
	// The record's bytes (Verify: digest, size, type, pixels), so the same
	// digest and pixels; NewImage holds them for the provider client.
	img, err := provider.NewImage(im.MediaType, data)
	if err != nil {
		return provider.Image{}, failure(PhotoCorrupt, "the stored photo is not one the provider client sends", false)
	}
	return img, nil
}

// generatePhoto is generate for a proposal asked for with a photo.
func (h *Handler) generatePhoto(ctx context.Context, org string, st started, attr provider.Attribution) (generation, error) {
	pr, v := st.proposal, st.version
	if pr.Image == nil || pr.Mode != string(provider.ModeEdit) || pr.Intent != "" {
		return generation{}, failure(InputInvalid, "a photo proposal is an edit with an image and no intent", false)
	}
	pc := &photoCall{image: *pr.Image}
	var ir model.ModelIR
	if err := model.Decode(v.IR, &ir); err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the base version does not decode", false)
	}
	pack, err := h.cfg.Packs.Lookup(ir.Domain)
	if err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the model's domain is not served by this worker", false)
	}
	concepts := photopipeline.Concepts(pack)
	if concepts == nil {
		return generation{photo: pc}, failure(PhotoNotSupported, "the model's domain takes no photos: describe the change in words", false)
	}
	if h.cfg.Segmenter == nil || h.cfg.Vision == nil {
		return generation{photo: pc}, failure("AI_"+strings.ToUpper(string(provider.CodeNotConfigured)), providerMessages[provider.CodeNotConfigured], false)
	}
	if !photopipeline.TakesImages(h.cfg.Vision) {
		return generation{photo: pc}, failure(ImageUnsupported, "the photo path's AI provider is off or does not take images; no provider call was made", false)
	}
	var pool idpool.Pool
	if err := json.Unmarshal(pr.IDPool, &pool); err != nil {
		return generation{photo: pc}, failure(InputInvalid, "the stored ID pool does not decode", false)
	}
	snaps, err := h.preload(ctx, org, st)
	if err != nil {
		return generation{photo: pc}, err
	}
	manifest, err := h.verify(ctx, org, pr.ID, snaps, &ir, v.DatasetBindings)
	if err != nil {
		return generation{photo: pc}, err
	}
	img, err := h.readImage(ctx, org, *pr.Image)
	if err != nil {
		return generation{photo: pc}, err
	}

	// The AI part (segmenter, checks, vision model, review, photo rules) is
	// internal/ai/photopipeline's, which the live photo smoke runs too.
	res, err := photopipeline.Propose(ctx, photopipeline.Clients{Segmenter: h.cfg.Segmenter, Vision: h.cfg.Vision}, photopipeline.Request{
		OrganizationID: org,
		Base:           aicontext.Version{OrganizationID: org, ModelID: v.ModelID, VersionID: v.ID, IR: &ir},
		BaseIR:         v.IR,
		Pack:           pack,
		Concepts:       concepts,
		Pool:           aicontext.Pool{OrganizationID: org, ProposalID: pr.ID, IDs: pool},
		Image:          img,
		OutputLocale:   pr.OutputLocale,
		Budget:         h.cfg.Budget,
		Attribution:    attr,
	}, photopipeline.Observer{
		Segmented: func(m provider.SegmentMetadata, n int, err error) { h.logSegment(ctx, m, n, err) },
		Answered:  func(m provider.Metadata, err error) { h.logCall(ctx, m, err) },
	})
	pc.segmenter, pc.segments = res.Segmenter, res.Segments
	if err != nil {
		if ctx.Err() != nil {
			return generation{}, err
		}
		var ce *photopipeline.ContextError
		var re *photopipeline.ReviewError
		switch {
		case errors.As(err, &ce) && ce.Code == aicontext.TooLarge:
			return generation{photo: pc}, failure("AI_CONTEXT_TOO_LARGE", providerMessages[provider.CodeContextTooLarge], false)
		case errors.As(err, &ce):
			h.cfg.Log.WarnContext(ctx, "building a photo proposal context failed", "organization_id", org, "proposal_id", pr.ID, "code", string(ce.Code))
			return generation{photo: pc}, failure(InputInvalid, "the proposal's stored request cannot be built into a context", false)
		case errors.As(err, &re):
			h.cfg.Log.ErrorContext(ctx, "reviewing a photo proposal failed", "organization_id", org, "proposal_id", pr.ID, "error", re.Err.Error())
			return generation{meta: res.Vision, photo: pc}, failure(InputInvalid, "the server could not review the answer against the stored base", false)
		}
		return generation{meta: res.Vision, photo: pc}, providerFailure(err)
	}
	outcome := res.Outcome
	if outcome.Status != review.Ready {
		return generation{outcome: outcome, meta: res.Vision, photo: pc, manifest: manifest}, nil
	}
	resolution, err := datasets.Resolve(ctx, snaps, org, outcome.Candidate, v.DatasetBindings)
	if err != nil {
		if ctx.Err() != nil {
			return generation{}, err
		}
		h.cfg.Log.ErrorContext(ctx, "the dataset binding stage failed after the provider answered", "organization_id", org, "proposal_id", pr.ID, "error", err.Error())
		return generation{meta: res.Vision, photo: pc}, failure(DatasetStorageFailed, "the dataset binding stage failed after the provider answered", false)
	}
	return generation{outcome: outcome.Refuse(withoutIR(resolution.Issues)), meta: res.Vision, photo: pc, manifest: manifest}, nil
}

// logSegment is the segmentation's operational line: labels, counts,
// latency, cost and the outcome code; never the image or a box. The
// reservations and the provider's request IDs are in the stored metadata
// and the spend ledger.
func (h *Handler) logSegment(ctx context.Context, m provider.SegmentMetadata, segments int, err error) {
	code := "OK"
	switch c := provider.CodeOf(err); {
	case err == nil:
	case c == "":
		code = "ERROR"
	default:
		code = "AI_" + strings.ToUpper(string(c))
	}
	h.cfg.Log.InfoContext(ctx, "ai segmenter call ended", "provider", m.Provider, "model", m.Model, "credential_label", m.Credential,
		"role", string(m.Role), "latency_ms", m.LatencyMillis, "boxes", segments, "code", code, "cost_nano_usd", m.CostNanoUSD)
	var pe *provider.Error
	if errors.As(err, &pe) && pe.Code == provider.CodeQuotaExceeded {
		h.cfg.Log.WarnContext(ctx, "a live AI spend limit refused a call", "role", string(m.Role), "limit", pe.Limit)
	}
	if m.SpendUnsettled {
		h.cfg.Log.WarnContext(ctx, "settling a live AI spend reservation failed", "cost_nano_usd", m.CostNanoUSD, "spend_unsettled", true)
	}
}

// photoImage is what the stored metadata says of the image.
type photoImage struct {
	Digest    string `json:"digest"`
	MediaType string `json:"media_type"`
	Width     int    `json:"width"`
	Height    int    `json:"height"`
}

// photoSegmenter is what the stored metadata says of the segmentation:
// T-055's metadata and how many objects the checked answer has.
type photoSegmenter struct {
	provider.SegmentMetadata
	Segments int `json:"segments"`
}

// photoMetadata is a photo proposal's provider metadata: the vision model's
// call (base, the generated row's provider_metadata), the image by its
// digest, type and size, and the segmentation.
func photoMetadata(base []byte, g generation) ([]byte, error) {
	if g.photo == nil {
		return base, nil
	}
	var doc map[string]jsontext.Value
	if err := json.Unmarshal(base, &doc); err != nil {
		return nil, err
	}
	im := g.photo.image
	image, err := json.Marshal(photoImage{Digest: im.SHA256, MediaType: im.MediaType, Width: im.Width, Height: im.Height})
	if err != nil {
		return nil, err
	}
	doc["image"] = image
	if g.photo.segmenter != nil {
		seg, err := json.Marshal(photoSegmenter{SegmentMetadata: *g.photo.segmenter, Segments: g.photo.segments})
		if err != nil {
			return nil, err
		}
		doc["segmenter"] = seg
	}
	return json.Marshal(doc, json.Deterministic(true))
}

// photoAuditMeta is auditMeta with what the audit records of the image and
// the segmentation (audit's photoCall fields): never the image or a box.
func photoAuditMeta(m provider.Metadata, p *photoCall) map[string]any {
	out := auditMeta(m)
	if p == nil {
		return out
	}
	out["image_content_hash"] = p.image.SHA256
	if s := p.segmenter; s != nil {
		out["segmenter"], out["segmenter_concepts"], out["segmenter_boxes"] = audit.Label(s.Provider), s.Concepts, p.segments
		out["segmenter_images"], out["segmenter_latency_ms"] = s.Images, s.LatencyMillis
		if l := audit.Label(s.Model); l != "" {
			out["segmenter_model"] = l
		}
		if len(s.SpendReservations) > 0 {
			out["segmenter_cost_nano_usd"], out["segmenter_spend_reservations"] = s.CostNanoUSD, len(s.SpendReservations)
			out["segmenter_spend_unsettled"] = s.SpendUnsettled
		}
	}
	return out
}
