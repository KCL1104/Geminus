// editedPhotoAnswer is the demo's vision answer with edit applied to the
// change that adds the n-th pool ID of kind.
func editedPhotoAnswer(t *testing.T, r *photoRig, kind string, n int, edit func(value map[string]any)) []byte {
	t.Helper()
	pool := poolIDs(t, r.st)
	var a map[string]any
	if err := json.Unmarshal(contracttest.PhotoAnswer(t, "electronics-line-demo", pool), &a); err != nil {
		t.Fatal(err)
	}
	found := false
	for _, c := range a["changes"].([]any) {
		v, ok := c.(map[string]any)["value"].(map[string]any)
		if ok && v["id"] == pool[kind][n] {
			edit(v)
			found = true
		}
	}
	if !found {
		t.Fatalf("no change adds %s %d", kind, n)
	}
	out, err := json.Marshal(a)
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestThePhotoRepair(t *testing.T) {
	var logs bytes.Buffer
	r := newPhotoRig(t, "electronics-line-demo", func(c *Config) { c.Log = observability.NewLogger(&logs, "worker") })
	r.script(-1)
	digest := r.demo.Segments.StoredDigest
	// The conveyor before ICT sends only half its boards on: its outgoing
	// probabilities do not add up (ROUTING_INVALID at the added queue).
	half := editedPhotoAnswer(t, r, "flow", 2, func(v map[string]any) { v["routing"].(map[string]any)["probability"] = 0.5 })
	r.vision.Script(provider.RoleModeler, digest, half)
	r.vision.ScriptRevision(provider.RoleModeler, digest, contracttest.PhotoAnswer(t, "electronics-line-demo", poolIDs(t, r.st)))
	gen, err := r.run(t, context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if gen.outcome.Status != review.Ready || gen.repair == nil || gen.repair.Outcome != repair.Ready || !gen.repair.Revised() {
		t.Fatalf("%s %+v %+v", gen.outcome.Status, gen.outcome.Validation, gen.repair)
	}
	if n := len(r.seg.Calls()); n != len(r.demo.Segments.Concepts) {
		t.Errorf("the segmenter was asked %d times, want once per concept (%d)", n, len(r.demo.Segments.Concepts))
	}
	reqs := r.vision.Requests()
	if len(reqs) != 2 {
		t.Fatalf("%d vision requests", len(reqs))
	}
	first, second := reqs[0].Prompt, reqs[1].Prompt
	if second.Revision == nil || second.User() != first.User() || len(second.Images) != 1 || second.Images[0].Digest != digest ||
		second.TemplateVersion != first.TemplateVersion+"+repair-0.1.0" || reqs[1].MaxOutputTokens != provider.ImageMaxOutputTokens {
		t.Errorf("the repair request: %q, %d images", second.TemplateVersion, len(second.Images))
	}
	if follow := second.Revision.User(); !bytes.Contains([]byte(follow), []byte(`"code":"ROUTING_INVALID"`)) {
		t.Errorf("the follow-up %s", follow)
	}
	_, p := row(t, r.st, gen)
	if p.GeneratedBy == nil || !p.GeneratedBy.RevisedAfterCheck || p.GeneratedBy.Segmenter == nil || p.GeneratedBy.Segmenter.Objects != 10 ||
		len(p.GeneratedBy.Segmenter.Boxes) != 10 {
		t.Errorf("generated by %+v", p.GeneratedBy)
	}
	m := eventOf(t, r.st, gen)
	if m["repair"] != "ready" || m["segmenter_boxes"] != 10 {
		t.Errorf("the audit %v", m)
	}
	var calls []float64
	for _, l := range bytes.Split(bytes.TrimSpace(logs.Bytes()), []byte("\n")) {
		var line map[string]any
		if err := json.Unmarshal(l, &line); err != nil {
			t.Fatal(err)
		}
		if line["msg"] == "ai provider call ended" {
			calls = append(calls, line["call_attempt"].(float64))
		}
	}
	if !slices.Equal(calls, []float64{1, 2}) {
		t.Errorf("the vision calls' lines say %v", calls)
	}
}

// The dataset binding stage refuses the first answer (an empirical
// distribution on a dataset the base does not bind): a refusal the repair
// follows like any; the second answer goes through the stage too.
func TestThePhotoBindingStageIsRepaired(t *testing.T) {
	r := newPhotoRig(t, "electronics-line-demo")
	r.script(-1)
	digest := r.demo.Segments.StoredDigest
	unbound := editedPhotoAnswer(t, r, "node", 1, func(v map[string]any) {
		v["service_time"] = map[string]any{"distribution": map[string]any{"type": "empirical", "samples_ref": "dataset:aoi_times"}}
	})
	r.vision.Script(provider.RoleModeler, digest, unbound)
	gen, err := r.run(t, context.Background())
	if err != nil {
		t.Fatal(err)
	}
	// Unscripted, the fake repeats its answer: refused again by the stage.
	if gen.outcome.Status != review.Invalid || gen.repair == nil || gen.repair.Outcome != repair.Invalid || len(r.vision.Requests()) != 2 {
		t.Fatalf("%s %+v, %d requests", gen.outcome.Status, gen.repair, len(r.vision.Requests()))
	}
	follow := r.vision.Requests()[1].Prompt.Revision.User()
	if !bytes.Contains([]byte(follow), []byte(`"code":"DATASET_BINDING_INVALID"`)) {
		t.Errorf("the follow-up %s", follow)
	}
	r = newPhotoRig(t, "electronics-line-demo")
	r.script(-1)
	r.vision.Script(provider.RoleModeler, digest, editedPhotoAnswer(t, r, "node", 1, func(v map[string]any) {
		v["service_time"] = map[string]any{"distribution": map[string]any{"type": "empirical", "samples_ref": "dataset:aoi_times"}}
	}))
	r.vision.ScriptRevision(provider.RoleModeler, digest, contracttest.PhotoAnswer(t, "electronics-line-demo", poolIDs(t, r.st)))
	if gen, err = r.run(t, context.Background()); err != nil || gen.outcome.Status != review.Ready || !gen.repair.Revised() {
		t.Errorf("repaired: %s %+v %v", gen.outcome.Status, gen.repair, err)
	}
}

// No repair when the vision model was never asked (no boxes) or its answer
// was ready the first time.
func TestNoPhotoRepairWithoutARefusedAnswer(t *testing.T) {
	r := newPhotoRig(t, "electronics-line-demo")
	gen, err := r.run(t, context.Background())
	if err != nil || gen.outcome.Status != review.NeedsInput || gen.repair != nil || len(r.vision.Requests()) != 0 {
		t.Errorf("no boxes: %s %+v %v", gen.outcome.Status, gen.repair, err)
	}
	r = newPhotoRig(t, "electronics-line-demo")
	r.script(-1)
	r.vision.Script(provider.RoleModeler, r.demo.Segments.StoredDigest, contracttest.PhotoAnswer(t, "electronics-line-demo", poolIDs(t, r.st)))
	if gen, err = r.run(t, context.Background()); err != nil || gen.outcome.Status != review.Ready || gen.repair != nil || len(r.vision.Requests()) != 1 {
		t.Errorf("ready at once: %s %+v %v", gen.outcome.Status, gen.repair, err)
	}
}
