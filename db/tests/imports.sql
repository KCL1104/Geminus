CREATE FUNCTION pg_temp.fail(msg text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('dt.collect', true) = 'on' THEN RAISE WARNING 'FAILED: %', msg;
  ELSE RAISE EXCEPTION 'FAILED: %', msg; END IF;
END $$;
CREATE FUNCTION pg_temp.must_fail(stmt text, state text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE got text; msg text;
BEGIN
  BEGIN
    EXECUTE stmt;
    RAISE EXCEPTION USING ERRCODE = 'P0099'; -- roll the unexpected success back
  EXCEPTION WHEN OTHERS THEN
    got := SQLSTATE; msg := SQLERRM;
  END;
  IF got = 'P0099' THEN
    PERFORM pg_temp.fail(format('expected SQLSTATE %s but the statement succeeded: %s', state, stmt));
  ELSIF got <> state THEN
    PERFORM pg_temp.fail(format('expected SQLSTATE %s but got %s (%s) for: %s', state, got, msg, stmt));
  END IF;
END $$;
CREATE FUNCTION pg_temp.check(ok boolean, what text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF ok IS NOT TRUE THEN PERFORM pg_temp.fail(what); END IF;
END $$;
