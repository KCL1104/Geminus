-- Records what the current role sees in each scope, one statement per
-- scope, so a scope's settings are set before its reads.
CREATE FUNCTION pg_temp.look(who text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE r record;
BEGIN
  FOR r IN SELECT * FROM scoped ORDER BY org LOOP
    PERFORM pg_temp.scope(r.org, r.usr);
    INSERT INTO seen VALUES (who, r.org, r.usr, pg_temp.seen_memberships(), pg_temp.seen_organizations(), pg_temp.other_rows());
  END LOOP;
END $$;

