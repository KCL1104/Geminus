-- Failures abort the run. For diagnosis only, `SET dt.collect = on` first
-- turns them into warnings so every failing case is listed in one run.
CREATE FUNCTION pg_temp.fail(msg text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF current_setting('dt.collect', true) = 'on' THEN RAISE WARNING 'FAILED: %', msg;
  ELSE RAISE EXCEPTION 'FAILED: %', msg; END IF;
END $$;
CREATE FUNCTION pg_temp.must_fail(stmt text, state text) RETURNS void LANGUAGE plpgsql AS $$
DECLARE got text; msg text;
BEGIN
  BEGIN
    EXECUTE stmt;
    RAISE EXCEPTION USING ERRCODE = 'P0099'; -- roll the unexpected success back
  EXCEPTION WHEN OTHERS THEN
    got := SQLSTATE; msg := SQLERRM;
  END;
  IF got = 'P0099' THEN
    PERFORM pg_temp.fail(format('expected SQLSTATE %s but the statement succeeded: %s', state, stmt));
  ELSIF got <> state THEN
    PERFORM pg_temp.fail(format('expected SQLSTATE %s but got %s (%s) for: %s', state, got, msg, stmt));
  END IF;
END $$;
CREATE FUNCTION pg_temp.check(ok boolean, what text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF ok IS NOT TRUE THEN PERFORM pg_temp.fail(what); END IF;
END $$;
-- How many rows a statement reports (UPDATE / DELETE ... RETURNING, SELECT).
CREATE FUNCTION pg_temp.rows(stmt text) RETURNS bigint LANGUAGE plpgsql AS $$
DECLARE n bigint;
BEGIN
  EXECUTE format('WITH r AS (%s) SELECT count(*) FROM r', stmt) INTO n;
  RETURN n;
END $$;
-- What the current role sees, as sorted text.
CREATE FUNCTION pg_temp.seen_memberships() RETURNS text LANGUAGE sql AS $$
  SELECT coalesce(string_agg(organization_id || ':' || user_id || ':' || role, ' '
                             ORDER BY organization_id COLLATE "C", user_id COLLATE "C"), '')
  FROM twin.memberships
$$;
CREATE FUNCTION pg_temp.seen_organizations() RETURNS text LANGUAGE sql AS $$
  SELECT coalesce(string_agg(id || ':' || name, ' ' ORDER BY id COLLATE "C"), '') FROM twin.organizations
$$;
-- Rows of every other twin table the API may read (that the current role
-- may read too).
CREATE FUNCTION pg_temp.other_rows() RETURNS text LANGUAGE plpgsql AS $$
DECLARE t text; n bigint; out text := '';
BEGIN
  FOR t IN SELECT c.relname FROM pg_class c JOIN pg_namespace s ON s.oid=c.relnamespace
           WHERE s.nspname='twin' AND c.relkind='r' AND c.relname NOT IN ('memberships','organizations')
             AND has_table_privilege('twin_api', c.oid, 'SELECT') AND has_table_privilege(current_user, c.oid, 'SELECT')
           ORDER BY c.relname LOOP
    EXECUTE format('SELECT count(*) FROM twin.%I', t) INTO n;
    IF n <> 0 THEN out := out || t || '=' || n || ' '; END IF;
  END LOOP;
  RETURN out;
END $$;
